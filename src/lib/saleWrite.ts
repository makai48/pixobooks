// Shared sale writer — single source of truth for online checkout AND
// offline-queue replay. Pure build step + Supabase execute step.
import { supabase } from "./supabase";
import { computeCartCost, computeTotals } from "./pos";
import { convertQuantity, validateTransactionQty } from "./uom";
import { mapSale } from "./mappers";
import { toError } from "./utils";
import { makeDocumentNumber } from "./docNumber";
import { getActiveBranchId } from "@/hooks/useBranches";
import { currentBusinessId } from "./tenant";
import { logAudit } from "./audit";
import type { CheckoutInput } from "@/hooks/useSales";
import type {
  PaymentStatus,
  DocumentType,
  Sale,
  Settings,
} from "@/types";

export type BuiltSale = {
  salePayload: Record<string, unknown>;
  paymentRow: Record<string, unknown> | null;
  nextInvoice: Settings["invoice"];
  loyaltyEarned: number;
  paid: number;
  due: number;
  status: PaymentStatus;
  docType: DocumentType;
  number: string;
};

/** UUID v1–v5 shape. `sales.customer_id` is a uuid column, so anything else
 *  (a legacy slug such as "cust-mtn", a stale draft id, or a phone number)
 *  would abort the whole checkout with Postgres 22P02. */
const UUID_RE =
  /^[0-9a-f]{8}-[0-9a-f]{4}-[1-5][0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/i;

export function isCustomerUuid(value: string | null | undefined): value is string {
  return typeof value === "string" && UUID_RE.test(value.trim());
}

export function buildSaleWrite(input: CheckoutInput): BuiltSale {
  const {
    lines,
    customerId,
    customerName,
    orderDiscountPct,
    paymentMethod,
    cashierId,
    cashierName,
    items,
    settings,
    loyaltyRedeemPoints = 0,
    amountPaid,
    dueDate,
  } = input;

  if (!lines.length) throw new Error("Cart is empty");

  // Central UOM gate (§4-7): discrete sale UOMs reject fractional qtys.
  // Runs for online checkout AND offline replay alike.
  if (input.uoms) {
    const byId = new Map(items.map((i) => [i.id, i]));
    for (const l of lines) {
      const it = byId.get(l.itemId);
      const check = validateTransactionQty(
        l.qty,
        it?.saleUnit || it?.baseUnit || "pc",
        input.uoms,
        { itemAllowDecimalQty: it?.allowDecimalQty, label: it?.name || "Item" }
      );
      if (!check.ok) throw new Error(check.reason);
    }
  }

  const redeemValue = settings.loyalty.enabled
    ? loyaltyRedeemPoints * settings.loyalty.dollarPerPoint
    : 0;

  // `sales.customer_id` is a uuid column. A legacy slug ("cust-mtn"), a stale
  // POS-draft id, or a phone number would abort the entire checkout with
  // Postgres 22P02. Keep the printed name, but only link a real uuid.
  const rawCustomerId = (customerId || "").trim();
  const linkedCustomerId = isCustomerUuid(rawCustomerId)
    ? rawCustomerId
    : null;

  const totals = computeTotals(lines, orderDiscountPct, settings, redeemValue);
  const cost = computeCartCost(lines, items);

  const loyaltyEarned =
    settings.loyalty.enabled && linkedCustomerId
      ? Math.floor(totals.total * settings.loyalty.pointsPerDollar)
      : 0;

  let paid = totals.total;
  let due = 0;
  let status: PaymentStatus = "paid";
  let docType: DocumentType = "receipt";

  if (paymentMethod === "credit") {
    paid = 0;
    due = totals.total;
    status = "credit";
    docType = "invoice";
  } else if (paymentMethod === "partial") {
    const p = Math.max(0, Math.min(totals.total, Number(amountPaid || 0)));
    paid = p;
    due = totals.total - p;
    status = due <= 0 ? "paid" : "partial";
    docType = due <= 0 ? "receipt" : "invoice";
  }

  if ((status === "credit" || status === "partial") && !linkedCustomerId) {
    throw new Error(
      rawCustomerId
        ? "That customer is not linked to a valid account, so credit cannot be tracked. Re-select the customer or add them again."
        : "Credit and partial sales require a registered customer so the balance can be tracked."
    );
  }

  if (settings.loyalty.enabled && loyaltyRedeemPoints > 0 && !linkedCustomerId) {
    throw new Error(
      "Loyalty points can only be redeemed for a registered customer."
    );
  }

  // Numbering: R/I + shop prefix + 15-digit local timestamp
  // (e.g. RPX261014193045237, IPX261014193045237 — see lib/docNumber).
  // Stamped ONCE at document creation: a queued/offline input carries its
  // number in `input.documentNumber` and it is reused verbatim — never
  // regenerated by retries, printing, edits, or sync replay.
  const queuedNumber = (input.documentNumber || "").trim();
  const number =
    queuedNumber || makeDocumentNumber(docType, settings.invoice.prefix);

  // Historical snapshot (§21): stamp each line with its saleUOM→base
  // factor so the row keeps meaning even if conversions change later.
  const byId = new Map(items.map((i) => [i.id, i]));
  const snapLines = lines.map((l) => {
    const it = byId.get(l.itemId);
    const fromUOM = l.unit || it?.saleUnit || it?.baseUnit || "pc";
    const baseUOM = it?.baseUnit || fromUOM;
    const f = convertQuantity(1, fromUOM, baseUOM, input.conversions ?? [], [], input.uoms ?? []);
    return { ...l, unitFactor: f ? f.value : 1 };
  });

  // ONE timestamp for the whole document. Calling the clock twice can land
  // on either side of a millisecond and leave `created_at` and `updated_at`
  // disagreeing — or the payment row stamped a moment after its sale.
  const stamp = input.createdAt || new Date().toISOString();

  const salePayload = {
    number,
    business_id: input.businessId ?? currentBusinessId() ?? undefined,
    // The authoritative RPC inserts via `jsonb_populate_record`, which fills
    // every column omitted from the payload with NULL — including columns
    // whose DEFAULT would otherwise apply. Stamp the transaction time here so
    // `created_at` is never null (and offline replay keeps the real sale time).
    created_at: stamp,
    updated_at: stamp,
    cashier_id: cashierId,
    cashier_name: cashierName,
    customer_id: linkedCustomerId,
    customer_name: customerName || null,
    lines: snapLines,
    subtotal: totals.subtotal,
    line_discount_total: totals.lineDiscountTotal,
    order_discount_pct: orderDiscountPct,
    order_discount_value: totals.orderDiscountValue,
    tax: totals.tax,
    total: totals.total,
    cost,
    profit: totals.total - totals.tax - cost,
    payment_method: paymentMethod,
    payment_status: status,
    document_type: docType,
    amount_paid: paid,
    amount_due: due,
    due_date: dueDate || null,
    loyalty_earned: loyaltyEarned,
    loyalty_redeemed: loyaltyRedeemPoints,
    branch_id: getActiveBranchId(),
  };

  const paymentRow =
    paid > 0
      ? {
          // `commit_sale_authoritative` populates the payment row field by
          // field, so a missing id / timestamp would insert NULL instead of
          // letting the table defaults run.
          id: newUuid(),
          created_at: stamp,
          business_id: input.businessId ?? currentBusinessId() ?? undefined,
          amount: paid,
          payment_method: paymentMethod === "partial" ? "cash" : paymentMethod,
          received_by: cashierId,
          received_by_name: cashierName,
          notes: paymentMethod === "partial" ? "Initial cash portion" : null,
        }
      : null;

  const nextInvoice = {
    ...settings.invoice,
    nextNumber: settings.invoice.nextNumber + 1,
  };

  return {
    salePayload,
    paymentRow,
    nextInvoice,
    loyaltyEarned,
    paid,
    due,
    status,
    docType,
    number,
  };
}

/**
 * Stamp a checkout input with its document number exactly once, at creation
 * time (online click or offline enqueue). Returns the input with
 * `documentNumber` set; every later build (local receipt, server write,
 * sync replay) reuses it verbatim. Pure — safe to call before enqueueing.
 * May throw the same validation errors as buildSaleWrite.
 */
export function stampCheckoutInput(input: CheckoutInput): CheckoutInput {
  const withBusiness: CheckoutInput = input.businessId
    ? input
    : { ...input, businessId: currentBusinessId() };
  // The sale timestamp is stamped at creation too, so a queued sale keeps the
  // moment it actually happened instead of the eventual replay time.
  const stamped: CheckoutInput = withBusiness.createdAt
    ? withBusiness
    : { ...withBusiness, createdAt: new Date().toISOString() };
  if ((stamped.documentNumber || "").trim()) return stamped;
  return { ...stamped, documentNumber: buildSaleWrite(stamped).number };
}

/**
 * Instant local receipt for offline sales. Builds the exact same numbers as
 * the server write will produce, stamped with a local `offline-<queueId>` id.
 * Shown immediately so the customer gets a receipt with no internet; the
 * queued op replays the stamped input on reconnect, so the server row keeps
 * the exact number printed on the receipt.
 */
export function buildLocalSale(input: CheckoutInput, queueId: string): Sale {
  const built = buildSaleWrite(input);
  const p = built.salePayload;
  const num = (v: unknown, d = 0) => (v == null ? d : Number(v));
  const str = (v: unknown, d = "") => (v == null ? d : String(v));
  return {
    id: `offline-${queueId}`,
    number: str(p.number),
    createdAt: str(p.created_at, new Date().toISOString()),
    cashierId: (p.cashier_id as string | null) ?? null,
    cashierName: str(p.cashier_name, "Unknown"),
    customerId: (p.customer_id as string | null) ?? null,
    customerName: (p.customer_name as string | null) ?? null,
    lines: input.lines,
    subtotal: num(p.subtotal),
    lineDiscountTotal: num(p.line_discount_total),
    orderDiscountPct: num(p.order_discount_pct),
    orderDiscountValue: num(p.order_discount_value),
    tax: num(p.tax),
    total: num(p.total),
    cost: num(p.cost),
    profit: num(p.profit),
    paymentMethod: p.payment_method as Sale["paymentMethod"],
    paymentStatus: p.payment_status as Sale["paymentStatus"],
    documentType: p.document_type as Sale["documentType"],
    amountPaid: num(p.amount_paid),
    amountDue: num(p.amount_due),
    dueDate: (p.due_date as string | null) ?? null,
    loyaltyEarned: num(p.loyalty_earned),
    loyaltyRedeemed: num(p.loyalty_redeemed),
    branchId: (p.branch_id as string | null) ?? null,
  };
}

/** RFC 4122 v4 id, with fallbacks for browsers without `crypto.randomUUID`. */
function newUuid(): string {
  const c = typeof crypto !== "undefined" ? crypto : undefined;
  if (c && typeof c.randomUUID === "function") return c.randomUUID();
  if (c && typeof c.getRandomValues === "function") {
    const b = c.getRandomValues(new Uint8Array(16));
    b[6] = (b[6] & 0x0f) | 0x40;
    b[8] = (b[8] & 0x3f) | 0x80;
    const h = Array.from(b, (x) => x.toString(16).padStart(2, "0")).join("");
    return `${h.slice(0, 8)}-${h.slice(8, 12)}-${h.slice(12, 16)}-${h.slice(16, 20)}-${h.slice(20)}`;
  }
  return `${Date.now()}-${Math.random().toString(36).slice(2)}`;
}

export async function executeSaleWrite(input: CheckoutInput): Promise<Sale> {
  const {
    customerName,
    cashierId,
    cashierName,
    cashierRole,
  } = input;

  // A stable id is generated up front so the stock movements can reference the
  // sale before it is committed. Together with the stamped document number it
  // makes checkout idempotent: a retried request finds the same sale row and
  // returns it without touching stock again.
  const built = buildSaleWrite(input);
  built.salePayload.id = newUuid();
  let saleData: Record<string, unknown> | null = null;
  let duplicate = false;

  // Preferred path: one server transaction (sale + payment + stock).
  const rpc = await supabase.rpc("commit_sale_authoritative", {
    p_sale: built.salePayload,
    p_payment: built.paymentRow,
  });
  if (!rpc.error) {
    saleData = (rpc.data?.sale ?? null) as Record<string, unknown> | null;
    duplicate = !!rpc.data?.duplicate;
  } else {
    console.error("commit_sale failed", rpc.error);
    throw toError(rpc.error, "Checkout failed — the ledger transaction was not committed");
  }

  if (!saleData) {
    throw new Error("Checkout failed");
  }
  // Idempotent replay: the document already exists with its payment and
  // movements; return it untouched.
  if (duplicate) {
    return mapSale(saleData);
  }

  const { salePayload, due, status, number } =
    built;
  const totals = { total: (salePayload.total as number) ?? 0 };

  // Invoice sequence, customer balances, loyalty and attendance are committed
  // by commit_sale. Keeping no client-side compensation path prevents partial
  // accounting when the browser closes after checkout.

  if (status !== "paid") {
    await logAudit(
      { id: cashierId || "", name: cashierName, role: cashierRole || undefined },
      `sale.${status}`,
      "sale",
      String(saleData.id),
      { number, total: totals.total, due, customer: customerName }
    );
  }

  return mapSale(saleData);
}


