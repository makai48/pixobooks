// Document numbering — R/I + PREFIX + L + YYMMDD + L + HHMMSS + L.
//
// Receipts: `R<PREFIX><L><YYMMDD><L><HHMMSS><L>`  (e.g. RPXK261014Q193045Z)
// Invoices: `I<PREFIX><L><YYMMDD><L><HHMMSS><L>`  (e.g. IPXK261014Q193045Z)
//
// One random separator letter (3 per document, A–Z excluding H/I/O)
// separates prefix/date, date/time, and terminates the number. The random
// separators were added with explicit admin approval. Milliseconds were
// deliberately dropped, so same-second uniqueness rests on the letters:
// a same-device repeat redraws them (bounded loop below), and a
// cross-device repeat is caught by the sales.number unique constraint
// (fresh-stamp retry at creation, `conflict` status on sync replay).
//
// Timezone strategy: the DEVICE'S LOCAL TIME, matching the existing
// business-day behavior (`todayISO`/`localISODate` in utils.ts — the shop's
// day, not UTC). All devices should run on network time (NTP/auto) so
// stamps are comparable; clock skew is a documented limitation, not a
// silently handled case (see LIMITATIONS below).
//
// Uniqueness strategy:
// - The number is stamped ONCE when the document is created (online click
//   or offline enqueue) and preserved verbatim through retries, printing,
//   offline storage, and sync replay. It is NEVER regenerated by sync/edit.
// - Same-device same-second repeats redraw their separator letters (bounded
//   loop) instead of duplicating visibly — deterministic and format-safe.
// - Cross-device same-second collisions keep BOTH transactions: the
//   loser gets a fresh creation-time stamp online, or a visible `conflict`
//   status for manual resolution during sync replay. Nothing is overwritten,
//   merged, or silently discarded, and the visible format never changes.
//
// LIMITATIONS (explicit, per spec):
// - Timestamps alone are not globally unique. Two devices with skewed
//   clocks (or the same second + same letters) and the same prefix/doc-kind
//   can produce the same visible number. Detection: the sales.number unique
//   constraint (HTTP 409 / PG 23505). Resolution: fresh-stamp retry at
//   creation time; `conflict` status (manual resolution) during replay.
// - The guards are per process: an app restart within the same second with
//   identical drawn letters could theoretically repeat. The 409
//   retry/conflict path covers it.

import type { DocumentType } from "@/types";

const pad2 = (n: number) => String(n).padStart(2, "0");

/** 6-digit `YYMMDD` date part in device-local time. */
export function formatDocDatePart(d: Date): string {
  return `${String(d.getFullYear()).slice(-2)}${pad2(d.getMonth() + 1)}${pad2(d.getDate())}`;
}

/** 6-digit `HHMMSS` time part in device-local time (no milliseconds). */
export function formatDocTimePart(d: Date): string {
  return `${pad2(d.getHours())}${pad2(d.getMinutes())}${pad2(d.getSeconds())}`;
}

/** 12-digit `YYMMDDHHMMSS` stamp in device-local time. */
export function formatDocTimestamp(d: Date): string {
  return formatDocDatePart(d) + formatDocTimePart(d);
}

/** Separator alphabet: A–Z excluding H, I, O (kept out because they read
 *  as other characters on print: I≈1, O≈0). 23 letters → 23^3 = 12,167
 *  combinations per second-stamp. */
export const SEPARATOR_LETTERS = "ABCDEFGJKMNPQRSTUVWXYZ";

/** One random separator letter: A–Z excluding H, I, O (23 letters).
 *  H/I/O are kept out because they read as other characters on print
 *  (I≈1, O≈0). Prefers crypto randomness. */
export function randomLetter(): string {
  const N = SEPARATOR_LETTERS.length;
  const pick = (i: number) => SEPARATOR_LETTERS[i % N];
  try {
    const g = globalThis.crypto;
    if (g && typeof g.getRandomValues === "function") {
      const buf = new Uint32Array(1);
      g.getRandomValues(buf);
      return pick(buf[0]);
    }
  } catch {
    // Fall through to Math.random.
  }
  return pick(Math.floor(Math.random() * N));
}

export type DocLetterTriple = [string, string, string];

/** Three random separator letters: prefix/date, date/time, trailing. */
export function randomLetters(): DocLetterTriple {
  return [randomLetter(), randomLetter(), randomLetter()];
}

// Last millisecond a number was issued in this process (internal ordering;
// the visible stamp carries seconds). Numbers issued in the current second,
// so a same-second repeat redraws its separator letters instead of
// duplicating visibly. The set resets whenever the second changes, so it
// never grows beyond one second's burst.
let lastStampMs = 0;
let lastSecondKey = "";
let secondNumbers = new Set<string>();

/** Reset the guards (tests only). */
export function resetDocNumberGuard(): void {
  lastStampMs = 0;
  lastSecondKey = "";
  secondNumbers = new Set<string>();
}

/**
 * Build a document number. `at` overrides "now" and `letters` overrides the
 * random separators (both tests only) — production always stamps the
 * creation moment with fresh random letters.
 */
export function makeDocumentNumber(
  docType: DocumentType,
  prefix: string,
  at?: Date,
  letters?: DocLetterTriple
): string {
  const now = (at ?? new Date()).getTime();
  const ms = now <= lastStampMs ? lastStampMs + 1 : now;
  lastStampMs = ms;
  const kind = docType === "invoice" ? "I" : "R";
  const d = new Date(ms);
  const date = formatDocDatePart(d);
  const time = formatDocTimePart(d);
  if (letters) {
    return `${kind}${prefix}${letters[0]}${date}${letters[1]}${time}${letters[2]}`;
  }
  const secondKey = `${kind}|${prefix}|${date}|${time}`;
  if (secondKey !== lastSecondKey) {
    lastSecondKey = secondKey;
    secondNumbers = new Set<string>();
  }
  // Redraw separators on a repeat within the same second: same-second
  // uniqueness rests on the letters, and two draws colliding is 1 in
  // 12,167 (23^3) per attempt.
  for (let i = 0; i < 25; i++) {
    const [l1, l2, l3] = randomLetters();
    const n = `${kind}${prefix}${l1}${date}${l2}${time}${l3}`;
    if (!secondNumbers.has(n)) {
      secondNumbers.add(n);
      return n;
    }
  }
  const [l1, l2, l3] = randomLetters();
  const fallback = `${kind}${prefix}${l1}${date}${l2}${time}${l3}`;
  secondNumbers.add(fallback);
  return fallback;
}

/**
 * Validate the visible format: leading R/I, then prefix, then
 * L + 6-digit date + L + 6-digit time + trailing L.
 */
export function isDocumentNumber(v: unknown): boolean {
  if (typeof v !== "string" || (v[0] !== "R" && v[0] !== "I")) return false;
  return /[A-Z]\d{6}[A-Z]\d{6}[A-Z]$/.test(v);
}
